#!/usr/bin/env node
// Build step: converts the GENERATED zero-dependency contract validators from
// packages/commerce-contracts/generated/ts/index.ts into plain JavaScript at
// src/acceptance/contracts.generated.js, so the acceptance runner can validate
// merchant responses against the locked schemas without a TypeScript toolchain
// and without trusting the binding generator's output. The generated TS is
// never modified. Run after contracts change; --check fails when the synced
// copy is stale.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const kitRoot = join(here, '..');
const monorepoSource = join(kitRoot, '..', '..', 'packages', 'commerce-contracts', 'generated', 'ts', 'index.ts');
const bundledSource = join(kitRoot, 'runtime', 'contracts', 'generated.ts');
const source = existsSync(monorepoSource) ? monorepoSource : bundledSource;
const target = join(kitRoot, 'src', 'acceptance', 'contracts.generated.js');
const check = process.argv.includes('--check');

const HEADER = '// Generated by kits/auteric-kit/scripts/sync-contracts.mjs from\n// packages/commerce-contracts/generated/ts/index.ts. Do not edit.\n';

export function syncedContracts() {
  const text = readFileSync(source, 'utf8');
  if (!text.includes('Do not edit')) {
    throw new Error(`refusing to sync: ${source} does not look like the generated contracts file`);
  }
  return HEADER + stripTypeScriptTypes(text, { mode: 'transform' });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!existsSync(source)) throw new Error(`contracts source not found at ${source}; restore the bundled contract source`);
  const output = syncedContracts();
  if (check) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current !== output) {
      console.error(`stale synced contracts: run node ${join('scripts', 'sync-contracts.mjs')} from kits/auteric-kit`);
      process.exitCode = 1;
    } else {
      console.log('synced contracts are up to date');
    }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, output);
    console.log(`synced ${source} -> ${target}`);
  }
}
